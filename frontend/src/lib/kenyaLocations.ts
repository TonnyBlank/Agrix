export const countyOptions = Object.keys(subCountyOptions);

export function normalizeLocationName(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function findCountyOption(county: string) {
  const normalizedCounty = normalizeLocationName(county);
  if (!normalizedCounty) return null;

  return countyOptions.find((option) => normalizeLocationName(option) === normalizedCounty) ?? null;
}

export function findCountyForSubCounty(subCounty: string) {
  const normalizedSubCounty = normalizeLocationName(subCounty);
  if (!normalizedSubCounty) return null;

  for (const [county, subCounties] of Object.entries(subCountyOptions)) {
    if (subCounties.some((candidate) => normalizeLocationName(candidate) === normalizedSubCounty)) {
      return county;
    }
  }

  return null;
}
